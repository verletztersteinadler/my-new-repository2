function sz(id: string, name: string, powerKw: number | null = null, steamKgH: number | null = null): Size {
  return { id, name, powerKw, steamKgH };
}

function series(item: {
  id: string;
  name: string;
  categoryId: CategoryId;
  kind: string;
  image: string;
  summary: string;
  feature: string;
  extra: string;
  powerMinKw?: number | null;
  powerMaxKw?: number | null;
  steamMinKgH?: number | null;
  steamMaxKgH?: number | null;
  tempMaxC?: number | null;
  pressureNote?: string | null;
  fuels?: FuelId[];
  sizes?: Size[];
  sizesNote?: string | null;
  powerNote?: string | null;
}): Series {
  return {
    id: item.id,
    name: item.name,
    categoryId: item.categoryId,
    kind: item.kind,
    image: item.image,
    summary: item.summary,
    powerMinKw: item.powerMinKw ?? null,
    powerMaxKw: item.powerMaxKw ?? null,
    steamMinKgH: item.steamMinKgH ?? null,
    steamMaxKgH: item.steamMaxKgH ?? null,
    tempMaxC: item.tempMaxC ?? null,
    pressureNote: item.pressureNote ?? null,
    fuels: item.fuels ?? [],
    feature: item.feature,
    extra: item.extra,
    powerNote: item.powerNote ?? null,
    sizes: item.sizes ?? [],
    sizesNote: item.sizesNote ?? null,
    aliases: [],
  };
}

