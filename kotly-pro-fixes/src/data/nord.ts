function size(name: string, powerKw: number | null): Size {
  return {
    id: `nord-${name.toLowerCase().replace(/[\s/]+/g, "-")}`,
    name,
    powerKw,
    steamKgH: null,
  };
}

function powerRow(label: string, values: number[]): Size[] {
  return values.map((kw) => size(`${label} ${kw}`, kw));
}

