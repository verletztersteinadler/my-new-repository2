function power(prefix: string, values: number[], idPrefix?: string): Series["sizes"] {
  return values.map((kw) => ({
    id: `wyberg-${idPrefix ?? prefix}-${kw}`,
    name: `${prefix.toUpperCase()} ${kw}`,
    powerKw: kw,
    steamKgH: null,
  }));
}

function boiler(
  id: string,
  name: string,
  kind: string,
  image: string,
  categoryId: string,
  values: number[],
  pressureNote: string,
  tempMaxC: number | null,
  fuels: FuelId[],
  feature: string,
  url: string,
  aliases: string[],
  extraNote: string,
  sizePrefix: string,
  sizeIdPrefix?: string,
): Series {
  return {
    id,
    name,
    categoryId,
    kind,
    image,
    summary:
      `${values[0]}–${values[values.length - 1]} кВт, ${values.length} типоразмеров` +
      (pressureNote ? `, ${pressureNote}` : "") +
      (tempMaxC != null ? `, вода до ${tempMaxC} °C.` : "."),
    powerMinKw: values[0],
    powerMaxKw: values[values.length - 1],
    steamMinKgH: null,
    steamMaxKgH: null,
    tempMaxC,
    pressureNote,
    fuels,
    feature,
    extra: `${checked} Источник: ${url}. ${extraNote}`,
    sizes: power(sizePrefix, values, sizeIdPrefix),
    sizesNote: null,
    aliases,
  };
}

