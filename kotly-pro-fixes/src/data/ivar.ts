function fmt(n: number): string {
  return n.toLocaleString("ru-RU");
}

function steamSeries(
  id: string,
  name: string,
  kind: string,
  rows: [number, number][],
  pressureNote: string,
  feature: string,
  extra: string,
): Series {
  return {
    id,
    name,
    categoryId: "steam",
    kind,
    image: "/catalog/steam.jpg",
    summary: `${fmt(rows[0][0])}–${fmt(rows[rows.length - 1][0])} кг/ч.`,
    powerMinKw: rows[0][1],
    powerMaxKw: rows[rows.length - 1][1],
    steamMinKgH: rows[0][0],
    steamMaxKgH: rows[rows.length - 1][0],
    tempMaxC: null,
    pressureNote,
    fuels: gasOilHeavy,
    feature,
    extra: `${checked} ${extra}`,
    sizes: rows.map(([kg, kw]) => ({
      id: `${id}-${kg}`,
      name: `${name.replace("I.VAR ", "")} ${kg}`,
      powerKw: kw,
      steamKgH: kg,
    })),
    sizesNote: "Модель = паропроизводительность, кг/ч; в описании типоразмера — полезная мощность, кВт.",
    aliases: [],
  };
}

function powerSeries(
  id: string,
  name: string,
  categoryId: string,
  kind: string,
  rows: [number, number][],
  pressureNote: string | null,
  tempMaxC: number | null,
  feature: string,
  extra: string,
  sizesNote: string | null,
  fuelsArg: FuelId[] = gasOilHeavy,
  image = "/catalog/firetube.jpg",
): Series {
  return {
    id,
    name,
    categoryId,
    kind,
    image,
    summary: `${fmt(rows[0][1])}–${fmt(rows[rows.length - 1][1])} кВт.`,
    powerMinKw: rows[0][1],
    powerMaxKw: rows[rows.length - 1][1],
    steamMinKgH: null,
    steamMaxKgH: null,
    tempMaxC,
    pressureNote,
    fuels: fuelsArg,
    feature,
    extra: `${checked} ${extra}`,
    sizes: rows.map(([model, kw]) => ({
      id: `${id}-${model}`,
      name: `${name.replace("I.VAR ", "")} ${model}`,
      powerKw: kw,
      steamKgH: null,
    })),
    sizesNote,
    aliases: [],
  };
}

