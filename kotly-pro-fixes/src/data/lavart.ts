function powerSizes(prefix: string, label: string, values: number[]): Series["sizes"] {
  return values.map((powerKw) => ({
    id: `${prefix}-${powerKw}`,
    name: `LAVART ${powerKw} ${label}`,
    powerKw,
    steamKgH: null,
  }));
}

function hw(
  id: string,
  name: string,
  kind: string,
  image: string,
  min: number,
  max: number,
  fuels: FuelId[],
  feature: string,
  url: string,
  aliases: string[],
  sizes: Series["sizes"],
  sizesNote: string | null,
  extraNote: string,
): Series {
  return {
    id,
    name,
    categoryId: "hw115",
    kind,
    image,
    summary: `${min.toLocaleString("ru-RU")}–${max.toLocaleString("ru-RU")} кВт, до 115 °C.`,
    powerMinKw: min,
    powerMaxKw: max,
    steamMinKgH: null,
    steamMaxKgH: null,
    tempMaxC: 115,
    pressureNote: null,
    fuels,
    feature,
    extra: `${checked} Источник: ${url}. ${extraNote}`,
    sizes,
    sizesNote,
    aliases,
  };
}

