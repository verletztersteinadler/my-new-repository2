function fmt(n: number): string {
  return n.toLocaleString("ru-RU");
}

function steamSeries(
  id: string,
  name: string,
  kind: string,
  rows: [string, number, number][],
  pressureNote: string,
  feature: string,
  extra: string,
  fuelsArg: FuelId[] = gasLiquid,
): Series {
  return {
    id,
    name,
    categoryId: "steam",
    kind,
    image: "/catalog/steam.jpg",
    summary: `${fmt(rows[0][1])}–${fmt(rows[rows.length - 1][1])} кг/ч.`,
    powerMinKw: rows[0][2],
    powerMaxKw: rows[rows.length - 1][2],
    steamMinKgH: rows[0][1],
    steamMaxKgH: rows[rows.length - 1][1],
    tempMaxC: null,
    pressureNote,
    fuels: fuelsArg,
    feature,
    extra: `${checked} ${extra}`,
    sizes: rows.map(([model, kg, kw]) => ({
      id: `${id}-${kg}`,
      name: `${name.replace("Erensan ", "")} ${model}`,
      powerKw: kw,
      steamKgH: kg,
    })),
    sizesNote: "Модель = паропроизводительность, кг/ч; в описании типоразмера — полезная мощность, кВт.",
    aliases: [],
  };
}

