function fmt(n: number): string {
  return n.toLocaleString("ru-RU");
}

function steamSeries(
  id: string,
  name: string,
  kind: string,
  rows: [string, number][],
  pressureNote: string,
  feature: string,
  extra: string,
  fuelsArg: FuelId[] = gasLiquid,
  image = "/catalog/steam.jpg",
): Series {
  return {
    id,
    name,
    categoryId: "steam",
    kind,
    image,
    summary: `${fmt(rows[0][1])}–${fmt(rows[rows.length - 1][1])} кг/ч.`,
    powerMinKw: null,
    powerMaxKw: null,
    steamMinKgH: rows[0][1],
    steamMaxKgH: rows[rows.length - 1][1],
    tempMaxC: null,
    pressureNote,
    fuels: fuelsArg,
    feature,
    extra: `${checked} ${extra}`,
    sizes: rows.map(([model, kg]) => ({
      id: `${id}-${model.toLowerCase().replace(/\s+/g, "-")}`,
      name: `${name.replace("Cannon Bono ", "")} ${model}`,
      powerKw: null,
      steamKgH: kg,
    })),
    sizesNote: "Модель = паропроизводительность «до», кг/ч (SG 200 — до 2 000 кг/ч).",
    aliases: [],
  };
}

